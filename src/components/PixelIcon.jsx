export default function PixelIcon({ genre, size = 64 }) {
  const rows = ICONS[genre] ?? ICONS.Puzzle;

  return (
    <svg width={size} height={size} viewBox="0 0 10 10" shapeRendering="crispEdges">
      {rows.map((row, y) =>
        row
          .split('')
          .map((cell, x) =>
            cell === '.' ? null : (
              <rect
                key={`${x}-${y}`}
                x={x}
                y={y}
                width="1"
                height="1"
                fill={cell === '#' ? '#111' : '#fff'}
              />
            ),
          ),
      )}
    </svg>
  );
}
